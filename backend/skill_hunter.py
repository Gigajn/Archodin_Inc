"""Skill Hunter & Toolsmith — grows the company's capability vault.

Flow (SRS §9.1): local vault -> whitelisted external registries -> Toolsmith.
Only four sources may ever be searched automatically (anti-malware rule):
the local vault, the MCP registry (Smithery), GitHub and PyPI.
Downloaded skills land in ``skills_vault/<skill_id>/`` and stay ``is_verified = 0``
until they pass a sandbox smoke test. ``pip install`` is never executed here: the
install command is only recorded for the sandbox runner to perform later.
"""

from __future__ import annotations

import json
import logging
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING, Any, Awaitable, Callable
from urllib.parse import quote

import httpx

from db import get_conn

if TYPE_CHECKING:  # pragma: no cover
    from smart_9router import SmartRouter

logger = logging.getLogger("aahc.skill_hunter")

VAULT_DIR = Path(__file__).resolve().parent / "skills_vault"

WHITELISTED_SOURCES = ("LOCAL", "MCP_REGISTRY", "GITHUB", "PYPI")

META_KEYS = frozenset({"name", "category", "source_type", "install_command"})
META_SCAN_LINES = 12

PYPI_API = "https://pypi.org/pypi/{name}/json"
GITHUB_SEARCH = "https://api.github.com/search/repositories"
MCP_REGISTRY = "https://registry.smithery.ai/servers"

MAX_HITS = 5

Transport = Callable[[httpx.Request], Awaitable[httpx.Response]]
Runner = Callable[..., Any]

_default_client: httpx.AsyncClient | None = None


@dataclass
class SearchHit:
    source: str
    name: str
    url: str
    description: str = ""
    install_command: str | None = None


@dataclass
class SkillInstallReport:
    skill_id: str
    status: str
    source: str
    vault_path: str
    verified: bool
    notes: list[str] = field(default_factory=list)


# --------------------------------------------------------------------------- utils


def slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.strip().lower()).strip("_") or "skill"


def _get_client() -> httpx.AsyncClient:
    global _default_client
    if _default_client is None:
        _default_client = httpx.AsyncClient(timeout=30.0)
    return _default_client


async def _send(request: httpx.Request, transport: Transport | None) -> httpx.Response:
    if transport is not None:
        return await transport(request)
    return await _get_client().send(request)


def _strip_fences(text: str) -> str:
    cleaned = (text or "").strip()
    match = re.search(r"```(?:json)?\s*(.*?)```", cleaned, re.DOTALL)
    if match:
        cleaned = match.group(1).strip()
    return cleaned


def read_skill_meta(skill_md: Path) -> dict[str, str]:
    """Parse the ``key: value`` metadata header from the first lines of a SKILL.md."""
    meta: dict[str, str] = {}
    try:
        lines = skill_md.read_text(encoding="utf-8").splitlines()[:META_SCAN_LINES]
    except OSError:
        return meta
    for line in lines:
        if ":" not in line:
            continue
        key, _, value = line.partition(":")
        key = key.strip().lstrip("#").strip().lower()
        if key in META_KEYS and key not in meta:
            meta[key] = value.strip()
    return meta


EXECUTOR_TEMPLATE = '''#!/usr/bin/env python3
"""Executor for the {name} skill.

TODO: implement {name}. Generated by the AAHC Skill Hunter.
"""

from __future__ import annotations

import argparse
import sys


def run(**kwargs):
    """Real implementation goes here."""
    raise NotImplementedError("TODO: implement {name}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Executor for {name}")
    parser.add_argument("--selftest", action="store_true", help="verify the executor loads")
    parser.add_argument("--query", default=None, help="payload for this skill")
    args = parser.parse_args(argv)
    if args.selftest:
        print("OK")
        return 0
    run(query=args.query)
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''


# ------------------------------------------------------------------ local registry


def search_local(name: str, vault_dir: Path = VAULT_DIR) -> list[SearchHit]:
    if not vault_dir.is_dir():
        return []
    needle = name.strip().lower()
    hits: list[SearchHit] = []
    for folder in sorted(p for p in vault_dir.iterdir() if p.is_dir()):
        skill_md = folder / "SKILL.md"
        if not skill_md.is_file():
            continue
        meta = read_skill_meta(skill_md)
        haystack = f"{folder.name} {meta.get('name', '')}".lower()
        if needle and needle not in haystack:
            continue
        hits.append(
            SearchHit(
                source="LOCAL",
                name=meta.get("name", folder.name),
                url=str(folder),
                description=f"Local skill folder {folder.name}",
                install_command=meta.get("install_command"),
            )
        )
    return hits


# -------------------------------------------------------------- external registries


async def search_pypi(name: str, transport: Transport | None = None) -> list[SearchHit]:
    request = httpx.Request("GET", PYPI_API.format(name=quote(name)))
    try:
        response = await _send(request, transport)
    except httpx.HTTPError as exc:
        logger.warning("skill_hunter: pypi lookup failed: %s", exc)
        return []
    if response.status_code != 200:
        return []
    try:
        info = response.json().get("info") or {}
    except ValueError:
        return []
    package = info.get("name") or name
    return [
        SearchHit(
            source="PYPI",
            name=package,
            url=f"https://pypi.org/project/{package}/",
            description=info.get("summary") or "",
            install_command=f"pip install {package}",
        )
    ]


async def search_github(
    name: str,
    transport: Transport | None = None,
    token: str | None = None,
) -> list[SearchHit]:
    import os

    headers = {
        "Accept": "application/vnd.github+json",
        "User-Agent": "AAHC-SkillHunter/0.1",
    }
    auth = token or os.environ.get("GITHUB_TOKEN") or ""
    if auth:
        headers["Authorization"] = f"Bearer {auth}"
    request = httpx.Request(
        "GET",
        GITHUB_SEARCH,
        params={"q": f"{name} in:name,description", "per_page": MAX_HITS},
        headers=headers,
    )
    try:
        response = await _send(request, transport)
    except httpx.HTTPError as exc:
        logger.warning("skill_hunter: github lookup failed: %s", exc)
        return []
    if response.status_code != 200:
        return []
    try:
        items = response.json().get("items") or []
    except ValueError:
        return []
    hits: list[SearchHit] = []
    for item in items[:MAX_HITS]:
        full_name = item.get("full_name")
        if not full_name:
            continue
        hits.append(
            SearchHit(
                source="GITHUB",
                name=full_name,
                url=item.get("html_url") or f"https://github.com/{full_name}",
                description=item.get("description") or "",
                install_command=f"git clone {item.get('clone_url') or ''}".strip(),
            )
        )
    return hits


async def search_mcp_registry(name: str, transport: Transport | None = None) -> list[SearchHit]:
    request = httpx.Request("GET", MCP_REGISTRY, params={"q": name})
    try:
        response = await _send(request, transport)
    except httpx.HTTPError as exc:
        logger.warning("skill_hunter: mcp registry lookup failed: %s", exc)
        return []
    if response.status_code != 200:
        return []
    try:
        data = response.json()
    except ValueError:
        return []
    entries = data.get("servers") if isinstance(data, dict) else data
    if not isinstance(entries, list):
        return []
    hits: list[SearchHit] = []
    for entry in entries[:MAX_HITS]:
        if not isinstance(entry, dict):
            continue
        qualified = entry.get("qualifiedName") or entry.get("name")
        if not qualified:
            continue
        url = entry.get("homepage") or entry.get("repository") or entry.get("url") or MCP_REGISTRY
        hits.append(
            SearchHit(
                source="MCP_REGISTRY",
                name=qualified,
                url=url,
                description=entry.get("description") or "",
                install_command=f"npx -y {qualified}",
            )
        )
    return hits


# ------------------------------------------------------------------- vault writing


def _write_skill(
    vault_dir: Path,
    skill_id: str,
    *,
    name: str,
    category: str,
    source_type: str,
    install_command: str | None,
    description: str,
    executor_code: str,
    requirements: str,
) -> Path:
    folder = vault_dir / skill_id
    folder.mkdir(parents=True, exist_ok=True)
    skill_md = folder / "SKILL.md"
    skill_md.write_text(
        "\n".join(
            [
                f"# name: {name}",
                f"category: {category}",
                f"source_type: {source_type}",
                f"install_command: {install_command or ''}",
                "",
                f"# {name}",
                "",
                description.strip() or f"Skill {name} installed by the AAHC Skill Hunter.",
                "",
                "## Usage",
                "",
                "```bash",
                "python tool_executor.py --query \"<payload>\"",
                "python tool_executor.py --selftest",
                "```",
                "",
            ]
        ),
        encoding="utf-8",
    )
    (folder / "tool_executor.py").write_text(executor_code, encoding="utf-8")
    (folder / "requirements.txt").write_text(requirements, encoding="utf-8")
    return skill_md


def _register_skill(
    skill_id: str,
    skill_name: str,
    category: str,
    source_type: str,
    install_command: str | None,
    skill_md_path: str,
    created_by: str,
    db_path: str | None = None,
) -> None:
    conn = get_conn(db_path)
    try:
        with conn:
            conn.execute(
                """
                INSERT OR REPLACE INTO skills_registry
                    (skill_id, skill_name, category, source_type, install_command, skill_md_path, is_verified, created_by)
                VALUES (?, ?, ?, ?, ?, ?, 0, ?)
                """,
                (skill_id, skill_name, category, source_type, install_command, skill_md_path, created_by),
            )
    finally:
        conn.close()


def _is_verified(skill_id: str, db_path: str | None = None) -> bool:
    conn = get_conn(db_path)
    try:
        row = conn.execute("SELECT is_verified FROM skills_registry WHERE skill_id = ?", (skill_id,)).fetchone()
        return bool(row["is_verified"]) if row else False
    finally:
        conn.close()


def sync_vault_to_registry(vault_dir: Path = VAULT_DIR, db_path: str | None = None) -> int:
    """Register every vault folder carrying a SKILL.md. Existing rows are untouched."""
    if not vault_dir.is_dir():
        return 0
    conn = get_conn(db_path)
    inserted = 0
    try:
        with conn:
            for folder in sorted(p for p in vault_dir.iterdir() if p.is_dir()):
                skill_md = folder / "SKILL.md"
                if not skill_md.is_file():
                    continue
                meta = read_skill_meta(skill_md)
                cursor = conn.execute(
                    """
                    INSERT OR IGNORE INTO skills_registry
                        (skill_id, skill_name, category, source_type, install_command, skill_md_path, is_verified, created_by)
                    VALUES (?, ?, ?, ?, ?, ?, 0, 'SYSTEM')
                    """,
                    (
                        folder.name,
                        meta.get("name", folder.name),
                        meta.get("category", "CORE"),
                        meta.get("source_type", "LOCAL_PYTHON"),
                        meta.get("install_command"),
                        str(skill_md),
                    ),
                )
                inserted += cursor.rowcount if cursor.rowcount > 0 else 0
    finally:
        conn.close()
    return inserted


def _default_runner(command: list[str], **kwargs: Any) -> Any:
    return subprocess.run(command, capture_output=True, text=True, **kwargs)


def verify_skill(
    skill_id: str,
    vault_dir: Path = VAULT_DIR,
    db_path: str | None = None,
    runner: Runner | None = None,
) -> bool:
    """Run the skill's sandbox smoke test; flip ``is_verified`` only on rc == 0."""
    folder = vault_dir / skill_id
    executor = folder / "tool_executor.py"
    if not executor.is_file():
        logger.warning("skill_hunter: no executor for %s", skill_id)
        return False

    run = runner or _default_runner
    try:
        proc = run([sys.executable, "tool_executor.py", "--selftest"], cwd=str(folder), timeout=60)
    except (subprocess.TimeoutExpired, OSError) as exc:
        logger.warning("skill_hunter: verification of %s failed: %s", skill_id, exc)
        return False

    if proc.returncode == 0:
        conn = get_conn(db_path)
        try:
            with conn:
                conn.execute("UPDATE skills_registry SET is_verified = 1 WHERE skill_id = ?", (skill_id,))
        finally:
            conn.close()
        return True

    stderr_tail = (proc.stderr or "")[-500:]
    logger.warning("skill_hunter: verification of %s exited %s: %s", skill_id, proc.returncode, stderr_tail)
    return False


# ------------------------------------------------------------------------ hunting


async def hunt_skill(
    name: str,
    router: "SmartRouter | None" = None,
    transport: Transport | None = None,
    vault_dir: Path = VAULT_DIR,
    db_path: str | None = None,
) -> SkillInstallReport:
    local_hits = search_local(name, vault_dir)
    if local_hits:
        folder = Path(local_hits[0].url)
        skill_id = folder.name
        verified = _is_verified(skill_id, db_path)
        return SkillInstallReport(
            skill_id=skill_id,
            status="ALREADY_LOCAL",
            source="LOCAL",
            vault_path=str(folder),
            verified=verified,
            notes=["Skill already present in the local vault."],
        )

    external: list[SearchHit] = []
    for finder in (search_mcp_registry, search_github, search_pypi):
        external = await finder(name, transport=transport)
        if external:
            break

    if not external:
        if router is None:
            return SkillInstallReport(
                skill_id=slugify(name),
                status="NOT_FOUND",
                source="NONE",
                vault_path="",
                verified=False,
                notes=["No hit in the whitelisted registries and no Toolsmith router provided."],
            )
        return await toolsmith_create(name, purpose=name, router=router, vault_dir=vault_dir, db_path=db_path)

    hit = external[0]
    skill_id = slugify(hit.name or name)
    source_type = {"PYPI": "API_WRAPPER", "MCP_SERVER": "MCP_SERVER"}.get(hit.source, "LOCAL_PYTHON")
    if hit.source == "GITHUB":
        source_type = "LOCAL_PYTHON"

    executor = EXECUTOR_TEMPLATE.format(name=skill_id)
    skill_md = _write_skill(
        vault_dir,
        skill_id,
        name=hit.name or skill_id,
        category="CORE",
        source_type=source_type,
        install_command=hit.install_command,
        description=hit.description or hit.url,
        executor_code=executor,
        requirements="",
    )
    _register_skill(
        skill_id,
        hit.name or skill_id,
        "CORE",
        source_type,
        hit.install_command,
        str(skill_md),
        "SKILL_HUNTER_AGENT",
        db_path,
    )
    verified = verify_skill(skill_id, vault_dir=vault_dir, db_path=db_path)
    return SkillInstallReport(
        skill_id=skill_id,
        status="INSTALLED" if verified else "VERIFY_FAILED",
        source=hit.source,
        vault_path=str(skill_md.parent),
        verified=verified,
        notes=[f"Source: {hit.source} ({hit.url})", f"Install command recorded: {hit.install_command or 'n/a'}"],
    )


async def toolsmith_create(
    name: str,
    purpose: str,
    router: "SmartRouter",
    vault_dir: Path = VAULT_DIR,
    db_path: str | None = None,
) -> SkillInstallReport:
    """Write a brand-new skill when no registry has one (the Toolsmith path)."""
    instruction = (
        "You are the AAHC Toolsmith. Write a brand-new Python skill for the company vault.\n"
        "Return ONLY one JSON object, no prose, no markdown fences, with this exact shape:\n"
        '{"skill_id": "<snake_case>", "skill_name": "<Title>", "category": "CORE|DEV|TRADING|MARKETING|CS", '
        '"source_type": "LOCAL_PYTHON|MCP_SERVER|API_WRAPPER", "purpose": "<one paragraph>", '
        '"executor_code": "<complete runnable python source>", "requirements": ["<pip package>", ...]}\n'
        "The executor MUST be a standalone script supporting `--selftest` (prints OK, no network) and `--query`."
    )
    result = await router.chat(
        messages=[
            {"role": "system", "content": instruction},
            {"role": "user", "content": f"Skill name: {name}\nPurpose: {purpose}"},
        ],
        cluster="CLUSTER_CODE",
        temperature=0.2,
        json_mode=True,
    )
    notes: list[str] = ["Generated by the Toolsmith path (no registry hit)."]
    try:
        data = json.loads(_strip_fences(result.content))
        if not isinstance(data, dict):
            raise ValueError("toolsmith payload is not a JSON object")
    except (json.JSONDecodeError, ValueError) as exc:
        logger.warning("skill_hunter: toolsmith payload invalid (%s); using template", exc)
        data = {}
        notes.append(f"LLM payload invalid ({exc}); fell back to the standard executor template.")

    skill_id = slugify(str(data.get("skill_id") or name))
    category = str(data.get("category") or "CORE")
    source_type = str(data.get("source_type") or "LOCAL_PYTHON")
    if source_type not in ("LOCAL_PYTHON", "MCP_SERVER", "API_WRAPPER"):
        source_type = "LOCAL_PYTHON"
    executor = str(data.get("executor_code") or "")
    if "--selftest" not in executor:
        executor = EXECUTOR_TEMPLATE.format(name=skill_id)
        notes.append("Generated executor lacked --selftest; standard template used instead.")
    requirements = data.get("requirements") or []
    requirements_text = "\n".join(str(item) for item in requirements) + ("\n" if requirements else "")

    skill_md = _write_skill(
        vault_dir,
        skill_id,
        name=str(data.get("skill_name") or name),
        category=category,
        source_type=source_type,
        install_command=f"pip install {' '.join(str(i) for i in requirements)}".strip() if requirements else None,
        description=str(data.get("purpose") or purpose),
        executor_code=executor,
        requirements=requirements_text,
    )
    _register_skill(
        skill_id,
        str(data.get("skill_name") or name),
        category,
        source_type,
        None,
        str(skill_md),
        "SKILL_HUNTER_AGENT",
        db_path,
    )
    verified = verify_skill(skill_id, vault_dir=vault_dir, db_path=db_path)
    return SkillInstallReport(
        skill_id=skill_id,
        status="INSTALLED" if verified else "VERIFY_FAILED",
        source="TOOLSMITH",
        vault_path=str(skill_md.parent),
        verified=verified,
        notes=notes,
    )
